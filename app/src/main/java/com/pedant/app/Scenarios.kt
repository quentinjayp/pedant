package com.pedant.app

import android.content.Context
import org.json.JSONObject

/** How formally Gemma speaks and translates: chosen for each conversation, changeable at any time. */
enum class Register(val title: String) {
    Formal("Formal"),
    Casual("Casual"),
}

/**
 * How hard the language is: the CEFR's first two bands, the same for every language. Gemma speaks at
 * the band, acts as the listener it assumes, and translates the learner's lines into what they can
 * say at it (instructions.json's bands); the quiz's word limits follow it. Chosen for each
 * conversation, first in New conversation, and remembered.
 */
enum class Band(val title: String, val about: String) {
    Basic("Basic", "A1–A2: short sentences and everyday words. The tutor speaks simply and helps."),
    Independent("Independent", "B1–B2: connected sentences, opinions and reasons, and the less routine."),
}

/**
 * How much help the learner gets, from the most to none. In [Beginner] (Repeat word) they're taken
 * through each phrase one word at a time before saying it whole; in [Intermediate] (Repeat phrase)
 * they say it whole straight away; in [FreeTalk] they say what they want in the language and the
 * tutor replies, with nothing to repeat. The names are kept from before the modes were renamed, as
 * the saved choice and saved quizzes use them.
 */
enum class Mode(val title: String, val about: String) {
    Beginner("Repeat word", "Say what you want in your own language, then say it one word at a time before the whole phrase."),
    Intermediate("Repeat phrase", "Say what you want in your own language, then repeat it back in the language until you get it right."),
    FreeTalk("Free talk", "Say what you want in the language, and the tutor replies. There's nothing to repeat."),
}

/**
 * How the phrase to say is given to the learner: said by the voice and shown as text, or only one
 * of the two. Never neither.
 */
enum class PhraseGuide(val title: String) {
    VoiceAndText("Voice guide and translation"),

    /** The text stays hidden until the first try, so the learner repeats what they heard. */
    VoiceOnly("Voice only"),

    /** The voice doesn't say the phrase, so the learner reads it. */
    TextOnly("Translation only"),
}

/**
 * A scenario for a conversation, from assets/scenarios.json: each band's are the situations the oral
 * exams use at its levels, written ahead (not generated by Gemma). [None] is No Scenario.
 */
data class Scenario(
    val id: String,
    /** Its name in New conversation's Scenario dropdown. */
    val title: String,
    /** The bands it's offered in; none for a retired one, kept only for saved conversations. */
    val bands: Set<Band>,
    /** For the learner, on the card. */
    val situation: String,
    /** Gemma's part, for its instructions; null for No Scenario. */
    val role: String?,
    /** What the learner does, on the card. */
    val prompts: List<String> = emptyList(),
    private val settings: Map<String, String> = emptyMap(),
) {
    /** Where the scene takes place in [language], somewhere the language is spoken; null if it has none. */
    fun setting(language: Language): String? = settings[language.code]

    companion object {
        val None = Scenario("none", "No Scenario", Band.entries.toSet(), "Talk about whatever you like.", role = null)

        private var all: List<Scenario> = emptyList()

        fun load(context: Context) {
            if (all.isNotEmpty()) return
            val json = JSONObject(context.assets.open("scenarios.json").bufferedReader().use { it.readText() })
            fun read(o: JSONObject, offered: Boolean) = Scenario(
                id = o.getString("id"),
                title = o.getString("title"),
                bands = if (!offered) emptySet() else o.getJSONArray("bands").let { a ->
                    (0 until a.length()).mapNotNull { i -> Band.entries.firstOrNull { it.name == a.getString(i) } }.toSet()
                },
                situation = o.getString("situation"),
                role = o.getString("role"),
                prompts = o.optJSONArray("prompts")?.let { a -> (0 until a.length()).map(a::getString) }.orEmpty(),
                settings = o.optJSONObject("settings")?.let { m -> m.keys().asSequence().associateWith(m::getString) }.orEmpty(),
            )
            fun list(name: String, offered: Boolean) = json.optJSONArray(name)?.let { a ->
                (0 until a.length()).map { read(a.getJSONObject(it), offered) }
            }.orEmpty()
            all = list("scenarios", offered = true) + list("retired", offered = false)
        }

        /** The scenarios offered at [band], in the file's order. */
        fun forBand(band: Band): List<Scenario> = all.filter { band in it.bands }

        /** The scenario called [id]; No Scenario for "none", for an older saved conversation's "Default", or for one not found. */
        fun byId(id: String): Scenario = all.firstOrNull { it.id == id } ?: None
    }
}

/** What's chosen in New conversation's Scenario dropdown. */
sealed interface ScenarioChoice {
    val title: String

    data object None : ScenarioChoice { override val title = "No Scenario" }

    /** One of the band's scenarios, drawn at random by the app when the conversation starts. */
    data object Random : ScenarioChoice { override val title = "Random" }

    /** Two of the band's scenarios drawn as cards, of which the learner picks one. */
    data object TwoCard : ScenarioChoice { override val title = "2 Card" }

    data class One(val scenario: Scenario) : ScenarioChoice { override val title get() = scenario.title }
}
